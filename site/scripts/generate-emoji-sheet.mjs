/**
 * Copies the Apple emoji spritesheet from emoji-datasource-apple into
 * static/emojis and writes the matching cell map that the emoji picker
 * uses to draw each emoji from the sheet.
 *
 * The sheet file name includes the emoji-datasource-apple version, because
 * static/emojis is served with immutable caching and a new layout must not
 * reuse a cached URL.
 *
 * Usage:  node scripts/generate-emoji-sheet.mjs
 * (run by `pnpm update-emojis`, with emoji-datasource-apple installed)
 */
import {
	copyFileSync,
	readdirSync,
	readFileSync,
	rmSync,
	writeFileSync,
} from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const siteDir = fileURLToPath(new URL("..", import.meta.url));
const datasourceDir = join(siteDir, "node_modules/emoji-datasource-apple");
const emojisDir = join(siteDir, "static/emojis");
const outputFile = join(siteDir, "src/components/IconField/emojiSheet.ts");

const { version } = JSON.parse(
	readFileSync(join(datasourceDir, "package.json"), "utf8"),
);
const emojis = JSON.parse(
	readFileSync(join(datasourceDir, "emoji.json"), "utf8"),
);

const sheetFile = `sheet-${version}.png`;
for (const file of readdirSync(emojisDir)) {
	if (file.startsWith("sheet-") && file !== sheetFile) {
		rmSync(join(emojisDir, file));
	}
}
const sheetPath = join(datasourceDir, "img/apple/sheets-256/64.png");
copyFileSync(sheetPath, join(emojisDir, sheetFile));

// Read the sheet size from the PNG header: each cell is 64px plus 1px of
// padding on every side.
const CELL_SIZE = 66;
const header = readFileSync(sheetPath).subarray(16, 24);
const columns = header.readUInt32BE(0) / CELL_SIZE;
const rows = header.readUInt32BE(4) / CELL_SIZE;
if (!Number.isInteger(columns) || !Number.isInteger(rows)) {
	throw new Error(`Unexpected spritesheet size: ${columns}x${rows} cells`);
}

const images = emojis.flatMap((emoji) => [
	emoji,
	...Object.values(emoji.skin_variations ?? {}),
]);
const cells = new Array(columns * rows).fill("");
for (const image of images) {
	if (image.has_img_apple) {
		cells[image.sheet_y * columns + image.sheet_x] = image.image.replace(
			/\.png$/,
			"",
		);
	}
}

writeFileSync(
	outputFile,
	`// Code generated by scripts/generate-emoji-sheet.mjs. DO NOT EDIT.

/**
 * The Apple emoji spritesheet in static/emojis, from emoji-datasource-apple
 * ${version}. Each cell is a 64px emoji with 1px of padding on every side.
 * \`cells\` lists the static/emojis file name drawn in each cell, row by row,
 * separated by commas; empty cells are empty strings.
 */
export const EMOJI_SHEET = {
	url: "/emojis/${sheetFile}",
	columns: ${columns},
	rows: ${rows},
	cells:
		"${cells.join(",")}",
};
`,
);
