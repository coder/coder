func TestBodyOpensWithContentBanner(t *testing.T) {
	t.Parallel()

	banner := docgenenv.GeneratedContentBanner
	for _, tt := range []struct {
		name string
		page string
		want bool
	}{
		{"AfterFrontMatter", "---\ntitle: x\n---\n\n" + banner + "\n\nBody\n", true},
		{"NoFrontMatter", banner + "\n# Title\n", true},
		{"InCodeBlock", "---\ntitle: x\n---\n\n```markdown\n" + banner + "\n```\n", false},
		{"LaterInBody", "# Title\n\n" + banner + "\n", false},
		{"UnclosedFrontMatter", "---\ntitle: x\n" + banner + "\n", false},
		{"Empty", "", false},
		// A Windows checkout with core.autocrlf converts the committed pages
		// to CRLF line endings.
		{"CRLFAfterFrontMatter", "---\r\ntitle: x\r\n---\r\n\r\n" + banner + "\r\n\r\nBody\r\n", true},
		{"CRLFNoFrontMatter", banner + "\r\n# Title\r\n", true},
		{"CRLFInCodeBlock", "---\r\ntitle: x\r\n---\r\n\r\n```markdown\r\n" + banner + "\r\n```\r\n", false},
		// The preamble the API generator writes, so a layout change there
		// fails here.
		{"GeneratedHeader", docgenenv.GeneratedHeader(docgenenv.Route{Title: "x", Description: "y"}) + "Body\n", true},
	} {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			require.Equal(t, tt.want, bodyOpensWithContentBanner([]byte(tt.page)))
		})
	}

	// Committed output of the CLI template, which builds its preamble inline,
	// and of the REST API postprocess index write, so a layout change in
	// either fails here after make gen.
	for _, page := range []string{
		"../../docs/reference/cli/index.md",
		"../../docs/reference/api/index.md",
	} {
		b, err := os.ReadFile(page)
		require.NoError(t, err)
		require.True(t, bodyOpensWithContentBanner(b), "%s: the body does not open with docgenenv.GeneratedContentBanner, so lint/docs-gen-filter stops treating this generator's pages as generated; restore the layout or update bodyOpensWithContentBanner", page)
	}
}

func TestGlobRegexp(t *testing.T) {
	t.Parallel()

	tests := []struct {
		glob    string
		match   []string
		noMatch []string
	}{
		{
			glob:    "docs/**",
			match:   []string{"docs", "docs/a.md", "docs/a/b/c.md"},
			noMatch: []string{"docsx/a.md", "site/docs/a.md"},
		},
		{
			glob:    "*.md",
			match:   []string{"README.md"},
			noMatch: []string{"docs/README.md"},
		},
		{
			glob:    "docs/reference/cli/**",
			match:   []string{"docs/reference/cli/users/create.md"},
			noMatch: []string{"docs/reference/api/users.md"},
		},
		{
			glob:    "docs/admin/*.md",
			match:   []string{"docs/admin/users.md"},
			noMatch: []string{"docs/admin/setup/index.md"},
		},
		{
			glob:    "docs/manifest.json",
			match:   []string{"docs/manifest.json"},
			noMatch: []string{"docs/manifestXjson", "docs/manifest.json.bak"},
		},
	}
	for _, tt := range tests {
		t.Run(tt.glob, func(t *testing.T) {
			t.Parallel()
			re, err := globRegexp(tt.glob)
			require.NoError(t, err)
			for _, p := range tt.match {
				require.True(t, re.MatchString(p), "%q should match %q", tt.glob, p)
			}
			for _, p := range tt.noMatch {
				require.False(t, re.MatchString(p), "%q should not match %q", tt.glob, p)
			}
		})
	}

	for _, glob := range []string{"", "**", "/**", "!docs/**", "docs/*/**", "docs/**/index.md", "docs/reference/**.md", `docs/\*.md`, "docs/?.md", "docs/{a,b}.md", "docs/[ab].md"} {
		_, err := globRegexp(glob)
		require.Error(t, err, "%q should be rejected", glob)
	}
}

func TestCheck(t *testing.T) {
	t.Parallel()

	filters := map[string][]string{
		"docs":     {"docs/**", "*.md"},
		"docs-gen": {"docs/manifest.json", "docs/reference/cli/**"},
	}
	tracked := []string{"docs/manifest.json", "docs/reference/cli/index.md", "docs/admin/users.md"}
	contents := map[string]string{
		"docs/reference/cli/index.md": "---\n# Code generated by make gen. DO NOT EDIT.\n---\n\n" + docgenenv.GeneratedContentBanner + "\n",
		"docs/admin/users.md":         "# Users\n\n```markdown\n" + docgenenv.GeneratedContentBanner + "\n```\n",
	}
	read := func(path string) ([]byte, error) { return []byte(contents[path]), nil }

	t.Run("Covered", func(t *testing.T) {
		t.Parallel()
		// docs/admin/users.md quotes the banner in a code block, which
		// doesn't make it generated.
		problems, err := check(filters, []string{"docs/manifest.json", "coderd/apidoc/swagger.json"}, tracked, read)
		require.NoError(t, err)
		require.Empty(t, problems)
	})

	t.Run("UncoveredGeneratedFile", func(t *testing.T) {
		t.Parallel()
		problems, err := check(filters, []string{"docs/admin/users.md", "GENERATED.md"}, tracked, read)
		require.NoError(t, err)
		require.Len(t, problems, 2)
		require.Contains(t, problems[0], "docs/admin/users.md")
		require.Contains(t, problems[1], "GENERATED.md")
	})

	t.Run("UncoveredBannerPage", func(t *testing.T) {
		t.Parallel()
		// cli.json keeps the narrowed pattern matching a tracked file, so the
		// only problems are the two pages with the banner.
		narrowed := map[string][]string{
			"docs":     filters["docs"],
			"docs-gen": {"docs/manifest.json", "docs/reference/cli/*.json"},
		}
		nested := append(slices.Clone(tracked), "docs/reference/cli/users/create.md", "docs/reference/cli/cli.json")
		nestedRead := func(path string) ([]byte, error) {
			if path == "docs/reference/cli/users/create.md" {
				return []byte("---\ntitle: create\n---\n\n" + docgenenv.GeneratedContentBanner + "\n"), nil
			}
			return read(path)
		}
		problems, err := check(narrowed, []string{"docs/manifest.json"}, nested, nestedRead)
		require.NoError(t, err)
		require.Len(t, problems, 2)
		require.Contains(t, problems[0], "docs/reference/cli/index.md")
		require.Contains(t, problems[1], "docs/reference/cli/users/create.md")
	})

	t.Run("StalePattern", func(t *testing.T) {
		t.Parallel()
		stale := map[string][]string{
			"docs":     filters["docs"],
			"docs-gen": append([]string{"docs/gone/**"}, filters["docs-gen"]...),
		}
		problems, err := check(stale, []string{"docs/manifest.json"}, tracked, read)
		require.NoError(t, err)
		require.Len(t, problems, 1)
		require.Contains(t, problems[0], `"docs/gone/**"`)
	})

	t.Run("MissingFilter", func(t *testing.T) {
		t.Parallel()
		_, err := check(map[string][]string{"docs": {"docs/**"}}, []string{"docs/manifest.json"}, tracked, read)
		require.ErrorContains(t, err, `"docs-gen"`)
	})

	t.Run("StatusQualifiedRule", func(t *testing.T) {
		t.Parallel()
		_, err := check(map[string][]string{"docs": {"docs/**"}, "docs-gen": {"map[added|modified:docs/new/**]"}}, []string{"docs/manifest.json"}, tracked, read)
		require.ErrorContains(t, err, `unsupported pattern "map[added|modified:docs/new/**]"`)
	})
}

func TestParseFilters(t *testing.T) {
	t.Parallel()

	workflow := `
jobs:
  changes:
    steps:
      - name: Checkout
        with:
          fetch-depth: 1
          persist-credentials: false
      - id: filter
        with:
          filters: |
            docs:
              - "docs/**"
            docs-gen:
              - "docs/manifest.json"
              - added|modified: "docs/new/**"
`
	filters, err := parseFilters([]byte(workflow))
	require.NoError(t, err)
	require.Equal(t, []string{"docs/**"}, filters["docs"])
	require.Equal(t, []string{"docs/manifest.json", "map[added|modified:docs/new/**]"}, filters["docs-gen"])

	_, err = parseFilters([]byte("jobs:\n  changes:\n    steps: []\n"))
	require.ErrorContains(t, err, `no step with id "filter"`)
}

// TestRepositoryWorkflow parses the real workflow so a restructured changes
// job fails here rather than only in make lint.
func TestRepositoryWorkflow(t *testing.T) {
	t.Parallel()

	workflow, err := os.ReadFile("../../.github/workflows/ci.yaml")
	require.NoError(t, err)
	filters, err := parseFilters(workflow)
	require.NoError(t, err)
	for _, name := range []string{"docs", "docs-gen"} {
		require.NotEmpty(t, filters[name], "filter %q", name)
		for _, p := range filters[name] {
			_, err := globRegexp(p)
			require.NoError(t, err, "filter %q pattern %q", name, p)
		}
	}
}
