package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"io"
	"log"
	"maps"
	"os"
	"regexp"
	"slices"
	"strings"

	dto "github.com/prometheus/client_model/go"
	"github.com/prometheus/common/expfmt"
	"golang.org/x/xerrors"

	"github.com/coder/coder/v2/scripts/atomicwrite"
)

var (
	staticMetricsFile    string
	docFile              string
	docTarget            string
	generatedMetricsFile string
	dryRun               bool
	sections             sectionFlags

	// generatedMarker and generatedEndMarker match the opening and closing
	// generated markers, named or unnamed, and capture the make target and the
	// section name. Matching markers that name another target is what turns a
	// stale pair into an error instead of a table that regeneration never
	// reaches.
	generatedMarker    = regexp.MustCompile(`<!-- Code generated by 'make ([^']+)'(?: section "([^"]+)")?\. DO NOT EDIT -->`)
	generatedEndMarker = regexp.MustCompile(`<!-- End generated by 'make ([^']+)'(?: section "([^"]+)")?\. -->`)
)

type metricFilter struct {
	prefixes        []string
	excludePrefixes []string
}

type documentSection struct {
	name   string
	filter metricFilter
}

type sectionFlags []documentSection

func (s *sectionFlags) String() string {
	values := make([]string, 0, len(*s))
	for _, section := range *s {
		values = append(values, section.name)
	}
	return strings.Join(values, ",")
}

func (s *sectionFlags) Set(value string) error {
	section, err := parseSection(value)
	if err != nil {
		return err
	}
	if slices.ContainsFunc(*s, func(existing documentSection) bool {
		return existing.name == section.name
	}) {
		return xerrors.Errorf("duplicate section %q", section.name)
	}
	*s = append(*s, section)
	return nil
}

func main() {
	flag.StringVar(&staticMetricsFile, "static-metrics", "scripts/metricsdocgen/metrics", "Path to static metrics file (manually maintained)")
	flag.StringVar(&generatedMetricsFile, "generated-metrics", "scripts/metricsdocgen/generated_metrics", "Path to generated metrics file (from scanner)")
	flag.StringVar(&docFile, "doc-file", "docs/admin/integrations/prometheus.md", "Path to the Markdown document to update")
	flag.StringVar(&docTarget, "doc-target", "", "Make target named in the generated markers (defaults to --doc-file). Set this when --doc-file points at a temporary copy")
	flag.Var(&sections, "section", "Named generated section, repeatable: NAME=prefix:PREFIX[,PREFIX...][,!EXCLUDED_PREFIX...]. "+
		"Each section replaces the content between its own `<!-- Code generated by 'make DOC' section \"NAME\". DO NOT EDIT -->` and "+
		"`<!-- End generated by 'make DOC' section \"NAME\". -->` markers. Without this flag the document's single unnamed marker pair is updated instead.")
	flag.BoolVar(&dryRun, "dry-run", false, "Dry run")
	flag.Parse()

	if docTarget == "" {
		docTarget = docFile
	}

	metrics, err := readAndMergeMetrics()
	if err != nil {
		log.Fatal("can't read metrics: ", err)
	}

	doc, err := readDoc()
	if err != nil {
		log.Fatalf("can't read %s: %v", docFile, err)
	}

	if len(sections) == 0 {
		doc, err = updateDefaultSection(doc, metrics, docTarget)
	} else {
		doc, err = updateDocumentSections(doc, metrics, docTarget, sections)
	}
	if err != nil {
		log.Fatalf("can't update %s: %v", docFile, err)
	}

	if dryRun {
		log.Println(string(doc))
		return
	}

	err = writeDoc(doc)
	if err != nil {
		log.Fatalf("can't write updated %s: %v", docFile, err)
	}
}

func parseSection(value string) (documentSection, error) {
	name, filterSpec, ok := strings.Cut(value, "=")
	if !ok || name == "" || filterSpec == "" {
		return documentSection{}, xerrors.New("section must have the form NAME=prefix:PREFIX")
	}
	for _, r := range name {
		if (r < 'a' || r > 'z') && (r < 'A' || r > 'Z') && (r < '0' || r > '9') && r != '-' && r != '_' {
			return documentSection{}, xerrors.Errorf("section name %q may contain only letters, numbers, hyphens, and underscores", name)
		}
	}

	kind, valuesSpec, ok := strings.Cut(filterSpec, ":")
	if !ok || valuesSpec == "" {
		return documentSection{}, xerrors.Errorf("section %q filter must have the form prefix:VALUE", name)
	}
	values := strings.Split(valuesSpec, ",")
	for _, value := range values {
		if value == "" {
			return documentSection{}, xerrors.Errorf("section %q contains an empty filter value", name)
		}
	}

	section := documentSection{name: name}
	if kind != "prefix" {
		return documentSection{}, xerrors.Errorf("section %q has unknown filter kind %q", name, kind)
	}
	for _, value := range values {
		if excluded, ok := strings.CutPrefix(value, "!"); ok {
			if excluded == "" {
				return documentSection{}, xerrors.Errorf("section %q contains an empty excluded prefix", name)
			}
			section.filter.excludePrefixes = append(section.filter.excludePrefixes, excluded)
			continue
		}
		section.filter.prefixes = append(section.filter.prefixes, value)
	}
	if len(section.filter.prefixes) == 0 {
		return documentSection{}, xerrors.Errorf("section %q requires at least one included prefix", name)
	}
	return section, nil
}

// readMetricsFromFile reads metrics from a single Prometheus text format file.
func readMetricsFromFile(path string) ([]*dto.MetricFamily, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, xerrors.Errorf("can't open metrics file %s: %w", path, err)
	}
	defer f.Close()

	var metrics []*dto.MetricFamily

	decoder := expfmt.NewDecoder(f, expfmt.NewFormat(expfmt.TypeTextPlain))
	for {
		var m dto.MetricFamily
		err = decoder.Decode(&m)
		if errors.Is(err, io.EOF) {
			break
		} else if err != nil {
			return nil, xerrors.Errorf("decoding metrics from %s: %w", path, err)
		}
		metrics = append(metrics, &m)
	}

	return metrics, nil
}

// readAndMergeMetrics reads metrics from both generated and static files,
// merges them, and returns a sorted list. Generated metrics are produced
// by the AST scanner that extracts metric definitions from the coder source
// code while static metrics are manually maintained (e.g., go_*, process_*,
// external dependencies).
// Note: Static metrics take priority over generated metrics, allowing manual
// overrides for metrics that can't be accurately extracted by the scanner.
func readAndMergeMetrics() ([]*dto.MetricFamily, error) {
	generatedMetrics, err := readMetricsFromFile(generatedMetricsFile)
	if err != nil {
		return nil, xerrors.Errorf("reading generated metrics: %w", err)
	}

	staticMetrics, err := readMetricsFromFile(staticMetricsFile)
	if err != nil {
		return nil, xerrors.Errorf("reading static metrics: %w", err)
	}

	metricsByName := make(map[string]*dto.MetricFamily)
	for _, m := range generatedMetrics {
		metricsByName[m.GetName()] = m
	}
	for _, m := range staticMetrics {
		metricsByName[m.GetName()] = m
	}

	return slices.SortedFunc(maps.Values(metricsByName), func(a, b *dto.MetricFamily) int {
		return strings.Compare(a.GetName(), b.GetName())
	}), nil
}

func readDoc() ([]byte, error) {
	doc, err := os.ReadFile(docFile)
	if err != nil {
		return nil, err
	}
	return doc, nil
}

// updateDefaultSection rewrites the document's single unnamed marker pair.
func updateDefaultSection(doc []byte, metricFamilies []*dto.MetricFamily, docTarget string) ([]byte, error) {
	if err := validateGeneratedMarkers(doc, docTarget, nil); err != nil {
		return nil, err
	}
	return replaceGeneratedSection(doc, defaultGeneratorPrefix(docTarget), defaultGeneratorSuffix(docTarget), metricFamilies)
}

// updateDocumentSections rewrites one marker pair per requested section.
func updateDocumentSections(doc []byte, metricFamilies []*dto.MetricFamily, docTarget string, sections []documentSection) ([]byte, error) {
	if err := validateGeneratedMarkers(doc, docTarget, sections); err != nil {
		return nil, err
	}
	var err error
	for _, section := range sections {
		filtered := filterMetricFamilies(metricFamilies, section.filter)
		if len(filtered) == 0 {
			return nil, xerrors.Errorf("section %q matches no metrics", section.name)
		}
		doc, err = replaceGeneratedSection(doc, namedGeneratorPrefix(docTarget, section.name), namedGeneratorSuffix(docTarget, section.name), filtered)
		if err != nil {
			return nil, xerrors.Errorf("updating section %q: %w", section.name, err)
		}
	}
	return doc, nil
}

// validateGeneratedMarkers rejects every generated marker in the document that
// the current invocation does not rewrite. A marker naming another make target,
// a named section that no --section flag claims, a marker of the mode that is
// not in use, and a repeated marker all keep a stale table under a header that
// reads "DO NOT EDIT", because only the requested markers get replaced and only
// the first occurrence of each is found. A closing marker with no opening one
// is rejected as well, since it reads as a section boundary that nothing owns.
func validateGeneratedMarkers(doc []byte, docTarget string, sections []documentSection) error {
	opened := map[string]int{}
	for _, match := range generatedMarker.FindAllSubmatch(doc, -1) {
		target, name := string(match[1]), string(match[2])
		if target != docTarget {
			return xerrors.Errorf("generated marker %q names make target %q, want %q", match[0], target, docTarget)
		}
		switch {
		case name == "" && len(sections) > 0:
			return xerrors.Errorf("document has an unnamed generated section, which --section mode never rewrites")
		case name != "" && len(sections) == 0:
			return xerrors.Errorf("document has generated section %q, which default mode never rewrites", name)
		case name != "" && !slices.ContainsFunc(sections, func(section documentSection) bool {
			return section.name == name
		}):
			return xerrors.Errorf("document has a generated section that no --section flag claims: %q", name)
		}
		opened[name]++
		if opened[name] > 1 {
			return xerrors.Errorf("document has %d generated markers for the same section: %q", opened[name], match[0])
		}
	}

	closed := map[string]int{}
	for _, match := range generatedEndMarker.FindAllSubmatch(doc, -1) {
		target, name := string(match[1]), string(match[2])
		if target != docTarget {
			return xerrors.Errorf("generated marker %q names make target %q, want %q", match[0], target, docTarget)
		}
		if opened[name] == 0 {
			return xerrors.Errorf("document has a closing marker with no opening marker: %q", match[0])
		}
		closed[name]++
		if closed[name] > 1 {
			return xerrors.Errorf("document has %d closing markers for the same section: %q", closed[name], match[0])
		}
	}
	return nil
}

func defaultGeneratorPrefix(docTarget string) []byte {
	return fmt.Appendf(nil, "<!-- Code generated by 'make %s'. DO NOT EDIT -->", docTarget)
}

func defaultGeneratorSuffix(docTarget string) []byte {
	return fmt.Appendf(nil, "<!-- End generated by 'make %s'. -->", docTarget)
}

func namedGeneratorPrefix(docTarget, name string) []byte {
	return fmt.Appendf(nil, "<!-- Code generated by 'make %s' section %q. DO NOT EDIT -->", docTarget, name)
}

func namedGeneratorSuffix(docTarget, name string) []byte {
	return fmt.Appendf(nil, "<!-- End generated by 'make %s' section %q. -->", docTarget, name)
}

func filterMetricFamilies(metricFamilies []*dto.MetricFamily, filter metricFilter) []*dto.MetricFamily {
	filtered := make([]*dto.MetricFamily, 0, len(metricFamilies))
	for _, metricFamily := range metricFamilies {
		name := metricFamily.GetName()
		matches := func(prefix string) bool { return strings.HasPrefix(name, prefix) }
		if !slices.ContainsFunc(filter.prefixes, matches) {
			continue
		}
		if slices.ContainsFunc(filter.excludePrefixes, matches) {
			continue
		}
		filtered = append(filtered, metricFamily)
	}
	return filtered
}

func replaceGeneratedSection(doc, prefix, suffix []byte, metricFamilies []*dto.MetricFamily) ([]byte, error) {
	// Both entry points run validateGeneratedMarkers first, so a repeated prefix
	// never reaches here through the CLI. The check keeps the invariant local:
	// rewriting the first pair of several silently leaves the rest stale.
	switch count := bytes.Count(doc, prefix); {
	case count == 0:
		return nil, xerrors.Errorf("generator prefix tag %q not found", prefix)
	case count > 1:
		return nil, xerrors.Errorf("generator prefix tag %q found %d times, want 1", prefix, count)
	}
	i := bytes.Index(doc, prefix)
	tableStartIndex := i + len(prefix)
	if tableStartIndex < len(doc) && doc[tableStartIndex] == '\n' {
		tableStartIndex++
	}

	j := bytes.Index(doc[tableStartIndex:], suffix)
	if j < 0 {
		return nil, xerrors.Errorf("generator suffix tag %q not found", suffix)
	}
	tableEndIndex := tableStartIndex + j

	var buffer bytes.Buffer
	_, _ = buffer.Write(doc[:tableStartIndex])
	_, _ = buffer.Write(renderMetricTable(metricFamilies))
	_, _ = buffer.Write(doc[tableEndIndex:])
	return buffer.Bytes(), nil
}

func renderMetricTable(metricFamilies []*dto.MetricFamily) []byte {
	var buffer bytes.Buffer
	_, _ = buffer.WriteString("\n| Name | Type | Description | Labels |\n")
	_, _ = buffer.WriteString("| - | - | - | - |\n")
	for _, mf := range metricFamilies {
		_, _ = buffer.WriteString("| `")
		_, _ = buffer.WriteString(mf.GetName())
		_, _ = buffer.WriteString("` | ")
		_, _ = buffer.WriteString(strings.ToLower(mf.GetType().String()))
		_, _ = buffer.WriteString(" | ")
		_, _ = buffer.WriteString(markdownCell(mf.GetHelp()))
		_, _ = buffer.WriteString(" | ")

		labels := map[string]struct{}{}
		for _, metric := range mf.GetMetric() {
			for _, label := range metric.GetLabel() {
				labels["`"+label.GetName()+"`"] = struct{}{}
			}
		}
		_, _ = buffer.WriteString(strings.Join(slices.Sorted(maps.Keys(labels)), " "))
		_, _ = buffer.WriteString(" |\n")
	}
	_ = buffer.WriteByte('\n')
	return buffer.Bytes()
}

// markdownCell makes a value safe to embed in a Markdown table cell. A pipe
// would shift the columns and a line break would split the row.
func markdownCell(value string) string {
	value = strings.ReplaceAll(value, "\r\n", " ")
	value = strings.ReplaceAll(value, "\n", " ")
	value = strings.ReplaceAll(value, "|", "\\|")
	return value
}

func writeDoc(doc []byte) error {
	return atomicwrite.File(docFile, doc)
}
