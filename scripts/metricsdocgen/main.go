package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"io"
	"log"
	"os"
	"slices"
	"strings"

	dto "github.com/prometheus/client_model/go"
	"github.com/prometheus/common/expfmt"
	"golang.org/x/xerrors"

	"github.com/coder/coder/v2/coderd/util/maps"
	"github.com/coder/coder/v2/scripts/atomicwrite"
)

var (
	staticMetricsFile    string
	prometheusDocFile    string
	generatedMetricsFile string
	dryRun               bool
	sections             sectionFlags

	generatorPrefix = []byte("<!-- Code generated by 'make docs/admin/integrations/prometheus.md'. DO NOT EDIT -->")
	generatorSuffix = []byte("<!-- End generated by 'make docs/admin/integrations/prometheus.md'. -->")
)

type metricFilter struct {
	prefixes        []string
	excludePrefixes []string
	names           map[string]struct{}
}

type documentSection struct {
	name   string
	filter metricFilter
}

type sectionFlags []documentSection

func (s *sectionFlags) String() string {
	values := make([]string, 0, len(*s))
	for _, section := range *s {
		values = append(values, section.name)
	}
	return strings.Join(values, ",")
}

func (s *sectionFlags) Set(value string) error {
	section, err := parseSection(value)
	if err != nil {
		return err
	}
	for _, existing := range *s {
		if existing.name == section.name {
			return xerrors.Errorf("duplicate section %q", section.name)
		}
	}
	*s = append(*s, section)
	return nil
}

func main() {
	flag.StringVar(&staticMetricsFile, "static-metrics", "scripts/metricsdocgen/metrics", "Path to static metrics file (manually maintained)")
	flag.StringVar(&generatedMetricsFile, "generated-metrics", "scripts/metricsdocgen/generated_metrics", "Path to generated metrics file (from scanner)")
	flag.StringVar(&prometheusDocFile, "prometheus-doc-file", "docs/admin/integrations/prometheus.md", "Path to the Markdown document to update")
	flag.Var(&sections, "section", "Named generated section filter: NAME=prefix:PREFIX[,!EXCLUDED_PREFIX] or NAME=names:METRIC[,METRIC]")
	flag.BoolVar(&dryRun, "dry-run", false, "Dry run")
	flag.Parse()

	metrics, err := readAndMergeMetrics()
	if err != nil {
		log.Fatal("can't read metrics: ", err)
	}

	doc, err := readPrometheusDoc()
	if err != nil {
		log.Fatal("can't read Prometheus doc: ", err)
	}

	if len(sections) == 0 {
		doc, err = updatePrometheusDoc(doc, metrics)
	} else {
		doc, err = updateDocumentSections(doc, metrics, sections)
	}
	if err != nil {
		log.Fatal("can't update Prometheus doc: ", err)
	}

	if dryRun {
		log.Println(string(doc))
		return
	}

	err = writePrometheusDoc(doc)
	if err != nil {
		log.Fatal("can't write updated Prometheus doc: ", err)
	}
}

func parseSection(value string) (documentSection, error) {
	name, filterSpec, ok := strings.Cut(value, "=")
	if !ok || name == "" || filterSpec == "" {
		return documentSection{}, xerrors.New("section must have the form NAME=prefix:PREFIX or NAME=names:METRIC")
	}
	for _, r := range name {
		if (r < 'a' || r > 'z') && (r < 'A' || r > 'Z') && (r < '0' || r > '9') && r != '-' && r != '_' {
			return documentSection{}, xerrors.Errorf("section name %q may contain only letters, numbers, hyphens, and underscores", name)
		}
	}

	kind, valuesSpec, ok := strings.Cut(filterSpec, ":")
	if !ok || valuesSpec == "" {
		return documentSection{}, xerrors.Errorf("section %q filter must have the form prefix:VALUE or names:VALUE", name)
	}
	values := strings.Split(valuesSpec, ",")
	for _, value := range values {
		if value == "" {
			return documentSection{}, xerrors.Errorf("section %q contains an empty filter value", name)
		}
	}

	section := documentSection{name: name}
	switch kind {
	case "prefix":
		for _, value := range values {
			if excluded, ok := strings.CutPrefix(value, "!"); ok {
				if excluded == "" {
					return documentSection{}, xerrors.Errorf("section %q contains an empty excluded prefix", name)
				}
				section.filter.excludePrefixes = append(section.filter.excludePrefixes, excluded)
				continue
			}
			section.filter.prefixes = append(section.filter.prefixes, value)
		}
		if len(section.filter.prefixes) == 0 {
			return documentSection{}, xerrors.Errorf("section %q requires at least one included prefix", name)
		}
	case "names":
		section.filter.names = make(map[string]struct{}, len(values))
		for _, value := range values {
			section.filter.names[value] = struct{}{}
		}
	default:
		return documentSection{}, xerrors.Errorf("section %q has unknown filter kind %q", name, kind)
	}
	return section, nil
}

// readMetricsFromFile reads metrics from a single Prometheus text format file.
func readMetricsFromFile(path string) ([]*dto.MetricFamily, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, xerrors.Errorf("can't open metrics file %s: %w", path, err)
	}
	defer f.Close()

	var metrics []*dto.MetricFamily

	decoder := expfmt.NewDecoder(f, expfmt.NewFormat(expfmt.TypeTextPlain))
	for {
		var m dto.MetricFamily
		err = decoder.Decode(&m)
		if errors.Is(err, io.EOF) {
			break
		} else if err != nil {
			return nil, xerrors.Errorf("decoding metrics from %s: %w", path, err)
		}
		metrics = append(metrics, &m)
	}

	return metrics, nil
}

// readAndMergeMetrics reads metrics from both generated and static files,
// merges them, and returns a sorted list. Generated metrics are produced
// by the AST scanner that extracts metric definitions from the coder source
// code while static metrics are manually maintained (e.g., go_*, process_*,
// external dependencies).
// Note: Static metrics take priority over generated metrics, allowing manual
// overrides for metrics that can't be accurately extracted by the scanner.
func readAndMergeMetrics() ([]*dto.MetricFamily, error) {
	generatedMetrics, err := readMetricsFromFile(generatedMetricsFile)
	if err != nil {
		return nil, xerrors.Errorf("reading generated metrics: %w", err)
	}

	staticMetrics, err := readMetricsFromFile(staticMetricsFile)
	if err != nil {
		return nil, xerrors.Errorf("reading static metrics: %w", err)
	}

	metricsByName := make(map[string]*dto.MetricFamily)
	for _, m := range generatedMetrics {
		metricsByName[m.GetName()] = m
	}
	for _, m := range staticMetrics {
		metricsByName[m.GetName()] = m
	}

	metrics := make([]*dto.MetricFamily, 0, len(metricsByName))
	for _, m := range metricsByName {
		metrics = append(metrics, m)
	}
	slices.SortFunc(metrics, func(a, b *dto.MetricFamily) int {
		return strings.Compare(a.GetName(), b.GetName())
	})
	return metrics, nil
}

func readPrometheusDoc() ([]byte, error) {
	doc, err := os.ReadFile(prometheusDocFile)
	if err != nil {
		return nil, err
	}
	return doc, nil
}

func updatePrometheusDoc(doc []byte, metricFamilies []*dto.MetricFamily) ([]byte, error) {
	return replaceGeneratedSection(doc, generatorPrefix, generatorSuffix, metricFamilies)
}

func updateDocumentSections(doc []byte, metricFamilies []*dto.MetricFamily, sections []documentSection) ([]byte, error) {
	var err error
	for _, section := range sections {
		filtered := filterMetricFamilies(metricFamilies, section.filter)
		doc, err = replaceGeneratedSection(doc, namedGeneratorPrefix(section.name), namedGeneratorSuffix(section.name), filtered)
		if err != nil {
			return nil, xerrors.Errorf("updating section %q: %w", section.name, err)
		}
	}
	return doc, nil
}

func namedGeneratorPrefix(name string) []byte {
	return fmt.Appendf(nil, "<!-- Code generated by metricsdocgen section %q. DO NOT EDIT -->", name)
}

func namedGeneratorSuffix(name string) []byte {
	return fmt.Appendf(nil, "<!-- End generated by metricsdocgen section %q. -->", name)
}

func filterMetricFamilies(metricFamilies []*dto.MetricFamily, filter metricFilter) []*dto.MetricFamily {
	filtered := make([]*dto.MetricFamily, 0, len(metricFamilies))
	for _, metricFamily := range metricFamilies {
		name := metricFamily.GetName()
		if _, ok := filter.names[name]; ok {
			filtered = append(filtered, metricFamily)
			continue
		}

		included := false
		for _, prefix := range filter.prefixes {
			if strings.HasPrefix(name, prefix) {
				included = true
				break
			}
		}
		if !included {
			continue
		}
		for _, prefix := range filter.excludePrefixes {
			if strings.HasPrefix(name, prefix) {
				included = false
				break
			}
		}
		if included {
			filtered = append(filtered, metricFamily)
		}
	}
	return filtered
}

func replaceGeneratedSection(doc, prefix, suffix []byte, metricFamilies []*dto.MetricFamily) ([]byte, error) {
	i := bytes.Index(doc, prefix)
	if i < 0 {
		return nil, xerrors.Errorf("generator prefix tag %q not found", prefix)
	}
	tableStartIndex := i + len(prefix)
	if tableStartIndex < len(doc) && doc[tableStartIndex] == '\n' {
		tableStartIndex++
	}

	j := bytes.Index(doc[tableStartIndex:], suffix)
	if j < 0 {
		return nil, xerrors.Errorf("generator suffix tag %q not found", suffix)
	}
	tableEndIndex := tableStartIndex + j

	var buffer bytes.Buffer
	_, _ = buffer.Write(doc[:tableStartIndex])
	_, _ = buffer.Write(renderMetricTable(metricFamilies))
	_, _ = buffer.Write(doc[tableEndIndex:])
	return buffer.Bytes(), nil
}

func renderMetricTable(metricFamilies []*dto.MetricFamily) []byte {
	var buffer bytes.Buffer
	_, _ = buffer.WriteString("\n| Name | Type | Description | Labels |\n")
	_, _ = buffer.WriteString("| - | - | - | - |\n")
	for _, mf := range metricFamilies {
		_, _ = buffer.WriteString("| `")
		_, _ = buffer.WriteString(mf.GetName())
		_, _ = buffer.WriteString("` | ")
		_, _ = buffer.WriteString(strings.ToLower(mf.GetType().String()))
		_, _ = buffer.WriteString(" | ")
		_, _ = buffer.WriteString(mf.GetHelp())
		_, _ = buffer.WriteString(" | ")

		labels := map[string]struct{}{}
		for _, metric := range mf.GetMetric() {
			for _, label := range metric.GetLabel() {
				labels["`"+label.GetName()+"`"] = struct{}{}
			}
		}
		_, _ = buffer.WriteString(strings.Join(maps.SortedKeys(labels), " "))
		_, _ = buffer.WriteString(" |\n")
	}
	_ = buffer.WriteByte('\n')
	return buffer.Bytes()
}

func writePrometheusDoc(doc []byte) error {
	return atomicwrite.File(prometheusDocFile, doc)
}
