import { execFile } from 'node:child_process';
import { lstat, mkdir, mkdtemp, readFile, rename, rm, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs, promisify } from 'node:util';
import { privateDirectory } from '../src/service.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const marker = '# Generated by claude-acp-bridge/scripts/install.mjs';
const quote = value => "'" + value.replaceAll("'", "'\\''") + "'";

async function main() {
  const { values } = parseArgs({ options: {
    'bin-dir': { type: 'string', default: join(homedir(), '.local/bin') },
    'state-dir': { type: 'string', default: join(process.env.XDG_STATE_HOME || join(homedir(), '.local/state'), 'coder-acp') },
    start: { type: 'boolean', default: false },
    model: { type: 'string' },
    help: { type: 'boolean', default: false },
  } });
  if (values.help) {
    console.log('Usage: ./install.sh [--bin-dir DIR] [--state-dir DIR] [--start [--model MODEL]]\nRequires Node.js 22+ and dependencies installed with npm ci --ignore-scripts.\nInstalls a launcher only; --start explicitly starts a detached broker, not a Claude session.');
    return;
  }
  if (process.platform !== 'linux' || Number(process.versions.node.split('.')[0]) < 22) {
    throw new Error('The workspace installer requires Linux and Node.js 22 or later.');
  }
  if (values.model && !values.start) throw new Error('--model requires --start; otherwise pass --model to coder-acp serve.');
  try {
    const require = createRequire(join(root, 'package.json'));
    require.resolve('@agentclientprotocol/sdk');
  } catch {
    throw new Error('Bridge dependencies are missing. Run npm ci --ignore-scripts in ' + root + ' first. The installer does not modify dependencies.');
  }
  const binDir = resolve(values['bin-dir']);
  const stateDir = resolve(values['state-dir']);
  const launcher = join(binDir, 'coder-acp');
  const stateFile = join(stateDir, 'bridge.json');
  const content = '#!/bin/sh\n' + marker + '\nexec ' + quote(process.execPath) + ' ' + quote(join(root, 'src/cli.mjs')) + ' --state ' + quote(stateFile) + ' "$@"\n';
  await mkdir(binDir, { recursive: true, mode: 0o755 });
  try {
    const info = await lstat(launcher);
    if (!info.isFile() || info.uid !== process.getuid() || !(await readFile(launcher, 'utf8')).startsWith('#!/bin/sh\n' + marker + '\n')) {
      throw new Error('Refusing to replace an unrelated file or symlink: ' + launcher);
    }
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  await privateDirectory(stateDir);
  const temporary = await mkdtemp(join(binDir, '.coder-acp-install-'));
  try {
    const file = join(temporary, 'coder-acp');
    await writeFile(file, content, { mode: 0o700, flag: 'wx' });
    await rename(file, launcher);
  } finally {
    await rm(temporary, { recursive: true, force: true });
  }
  console.log('Installed ' + launcher + '\nSource must remain at ' + root + '\nPrivate state: ' + stateDir);
  console.log('Make ' + binDir + ' available in the Coder agent PATH, including non-interactive SSH. Shell profile edits alone are not sufficient.');
  if (values.start) {
    const args = ['serve', '--detach'];
    if (values.model) args.push('--model', values.model);
    const { stdout, stderr } = await promisify(execFile)(launcher, args);
    process.stdout.write(stdout);
    process.stderr.write(stderr);
  } else {
    console.log('Broker not started. Run: ' + quote(launcher) + ' serve --detach');
  }
}

main().catch(error => {
  // execFile.message embeds the command; forward only the CLI's safe diagnostic.
  console.error(error.stderr?.trim() || error.message);
  process.exitCode = 1;
});
