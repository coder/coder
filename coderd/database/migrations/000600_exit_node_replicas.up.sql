CREATE TABLE exit_node_replicas (
	id uuid PRIMARY KEY,
	exit_node_id uuid NOT NULL REFERENCES exit_nodes(id) ON DELETE CASCADE,
	hostname text NOT NULL DEFAULT '',
	version text NOT NULL DEFAULT '',
	wireguard_endpoints text[] NOT NULL DEFAULT '{}',
	policy_hash text NOT NULL DEFAULT '',
	created_at timestamptz NOT NULL,
	started_at timestamptz NOT NULL,
	updated_at timestamptz NOT NULL,
	stopped_at timestamptz
);

COMMENT ON TABLE exit_node_replicas IS 'Running processes for an exit node. Each process has its own replica ID and heartbeat.';
COMMENT ON COLUMN exit_node_replicas.id IS 'Random identifier generated by the replica process.';
COMMENT ON COLUMN exit_node_replicas.exit_node_id IS 'Logical exit node this replica belongs to.';
COMMENT ON COLUMN exit_node_replicas.hostname IS 'Hostname reported by the replica process.';
COMMENT ON COLUMN exit_node_replicas.version IS 'Coder version reported by the replica process.';
COMMENT ON COLUMN exit_node_replicas.wireguard_endpoints IS 'Public ip:port pairs agents may use for direct WireGuard connections to the replica.';
COMMENT ON COLUMN exit_node_replicas.policy_hash IS 'Hash of the policy the replica enforces, so coderd can flag replicas of one exit node that disagree.';
COMMENT ON COLUMN exit_node_replicas.created_at IS 'Time the replica was first registered.';
COMMENT ON COLUMN exit_node_replicas.started_at IS 'Time the current replica process started.';
COMMENT ON COLUMN exit_node_replicas.updated_at IS 'Last heartbeat. A replica is live while stopped_at IS NULL and updated_at is recent.';
COMMENT ON COLUMN exit_node_replicas.stopped_at IS 'Set by explicit deregistration; a stopped replica may not re-register.';

CREATE INDEX exit_node_replicas_exit_node_id_idx ON exit_node_replicas (exit_node_id);

ALTER TABLE exit_nodes
	DROP COLUMN version,
	DROP COLUMN last_seen_at,
	DROP COLUMN wireguard_endpoints;
