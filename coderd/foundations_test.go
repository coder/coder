func TestFoundationStandaloneLifecycle(t *testing.T) {
	t.Parallel()
	client, db := newTemplateResourceClient(t)
	owner := coderdtest.CreateFirstUser(t, client)
	ctx := t.Context()
	//nolint:gocritic // Simulate authoritative worker results without external infrastructure.
	systemCtx := dbauthz.AsSystemRestricted(ctx)
	f, err := client.CreateFoundation(ctx, owner.OrganizationID, codersdk.CreateFoundationRequest{Name: "standalone", ProvisionerTags: map[string]string{"region": "east"}})
	require.NoError(t, err)
	require.Nil(t, f.TemplateID)
	require.Empty(t, f.Runs)
	require.Equal(t, []codersdk.FoundationResource{}, f.Resources)
	require.True(t, f.ResourcesAvailable)
	rev, err := client.CreateFoundationRevision(ctx, owner.OrganizationID, f.ID, codersdk.CreateTemplateResourceRevisionRequest{Source: "# Terraform root"})
	require.NoError(t, err)
	require.Equal(t, f.ID, rev.FoundationID)
	plan, err := client.CreateFoundationRun(ctx, owner.OrganizationID, f.ID, codersdk.CreateTemplateResourceRunRequest{RevisionID: rev.ID, Action: "plan"})
	require.NoError(t, err)
	listed, err := client.OrganizationProvisionerJob(ctx, owner.OrganizationID, plan.Job.ID)
	require.NoError(t, err)
	require.Equal(t, &f.ID, listed.Metadata.FoundationID)
	require.Equal(t, f.Name, listed.Metadata.FoundationName)
	require.Equal(t, uuid.Nil, listed.Metadata.TemplateID)
	jobs, err := client.OrganizationProvisionerJobs(ctx, owner.OrganizationID, &codersdk.OrganizationProvisionerJobsOptions{IDs: []uuid.UUID{plan.Job.ID}})
	require.NoError(t, err)
	require.Len(t, jobs, 1)
	require.Equal(t, listed, jobs[0])
	job, err := db.GetProvisionerJobByID(systemCtx, plan.Job.ID)
	require.NoError(t, err)
	require.Equal(t, "east", job.Tags["region"])
	require.Equal(t, provisionersdk.ScopeOrganization, job.Tags[provisionersdk.TagScope])
	require.Empty(t, job.Tags[provisionersdk.TagOwner])
	require.Equal(t, provisionersdk.TemplateResourcesCapabilityVersion, job.Tags[provisionersdk.TagTemplateResources])
	_, err = client.UpdateFoundation(ctx, owner.OrganizationID, f.ID, codersdk.UpdateFoundationRequest{Name: "renamed", ProvisionerTags: map[string]string{"region": "west"}})
	require.NoError(t, err)
	job, err = db.GetProvisionerJobByID(systemCtx, plan.Job.ID)
	require.NoError(t, err)
	require.Equal(t, "east", job.Tags["region"], "queued routing is immutable")
	require.Equal(t, http.StatusConflict, coderdtest.SDKError(t, client.DeleteFoundation(ctx, owner.OrganizationID, f.ID)).StatusCode())
	require.NoError(t, client.CancelFoundationRun(ctx, owner.OrganizationID, f.ID, plan.ID))
	apply, err := client.CreateFoundationRun(ctx, owner.OrganizationID, f.ID, codersdk.CreateTemplateResourceRunRequest{RevisionID: rev.ID, Action: "apply"})
	require.NoError(t, err)
	job, err = db.GetProvisionerJobByID(systemCtx, apply.Job.ID)
	require.NoError(t, err)
	require.Equal(t, "west", job.Tags["region"])
	state, err := db.CompleteTemplateResourceRun(systemCtx, database.CompleteTemplateResourceRunParams{FoundationID: f.ID, RunID: uuid.NullUUID{UUID: apply.ID, Valid: true}, Status: "applied", State: []byte(`{"version":4,"resources":[{"mode":"managed","type":"terraform_data","name":"example","instances":[{"attributes":{"input":"private authoritative checkpoint"}}]}]}`), Outputs: json.RawMessage(`{"value":"public"}`), AppliedRevisionID: uuid.NullUUID{UUID: rev.ID, Valid: true}, CheckpointRevisionID: uuid.NullUUID{UUID: rev.ID, Valid: true}, UpdatedAt: dbtime.Now()})
	require.NoError(t, err)
	inventory, err := client.Foundation(ctx, owner.OrganizationID, f.ID)
	require.NoError(t, err)
	require.True(t, inventory.ResourcesAvailable)
	require.Equal(t, []codersdk.FoundationResource{{Address: "terraform_data.example", Type: "terraform_data", Name: "example", Instances: 1}}, inventory.Resources)
	response, err := client.Request(ctx, http.MethodGet, "/api/v2/organizations/"+owner.OrganizationID.String()+"/foundations/"+f.ID.String(), nil)
	require.NoError(t, err)
	defer response.Body.Close()
	body, err := io.ReadAll(response.Body)
	require.NoError(t, err)
	require.NotContains(t, string(body), "private authoritative checkpoint")
	require.NotContains(t, string(body), "attributes")
	member, _ := coderdtest.CreateAnotherUser(t, client, owner.OrganizationID)
	_, err = member.Foundation(ctx, owner.OrganizationID, f.ID)
	require.Equal(t, http.StatusNotFound, coderdtest.SDKError(t, err).StatusCode(), "inventory inherits Foundation read permissions")
	memberList, err := member.Foundations(ctx, owner.OrganizationID)
	require.NoError(t, err)
	require.Empty(t, memberList)
	require.Equal(t, http.StatusConflict, coderdtest.SDKError(t, client.DeleteFoundation(ctx, owner.OrganizationID, f.ID)).StatusCode())
	destroy, err := client.CreateFoundationRun(ctx, owner.OrganizationID, f.ID, codersdk.CreateTemplateResourceRunRequest{RevisionID: rev.ID, Action: "destroy"})
	require.NoError(t, err)
	// A queued destroy canceled before acquisition is safe to retry explicitly.
	require.NoError(t, client.CancelFoundationRun(ctx, owner.OrganizationID, f.ID, destroy.ID))
	retry, err := client.CreateFoundationRun(ctx, owner.OrganizationID, f.ID, codersdk.CreateTemplateResourceRunRequest{RevisionID: rev.ID, Action: "destroy"})
	require.NoError(t, err)
	require.NotEqual(t, destroy.ID, retry.ID)
	retained, err := db.GetTemplateResourceState(systemCtx, f.ID)
	require.NoError(t, err)
	require.Equal(t, state.State, retained.State)
	_, err = db.CompleteTemplateResourceRun(systemCtx, database.CompleteTemplateResourceRunParams{FoundationID: f.ID, RunID: uuid.NullUUID{UUID: retry.ID, Valid: true}, Status: "destroyed", State: []byte(`{"resources":[]}`), Outputs: json.RawMessage(`{}`), UpdatedAt: dbtime.Now()})
	require.NoError(t, err)
	inventory, err = client.Foundation(ctx, owner.OrganizationID, f.ID)
	require.NoError(t, err)
	require.True(t, inventory.ResourcesAvailable)
	require.Equal(t, []codersdk.FoundationResource{}, inventory.Resources)
	require.NoError(t, client.DeleteFoundation(ctx, owner.OrganizationID, f.ID))
	_, err = client.Foundation(ctx, owner.OrganizationID, f.ID)
	require.Equal(t, http.StatusNotFound, coderdtest.SDKError(t, err).StatusCode())
	stored, err := db.GetTemplateResourceRevisionByID(systemCtx, rev.ID)
	require.NoError(t, err)
	require.Equal(t, f.ID, stored.FoundationID, "history survives soft deletion")
}

func TestFoundationBindingAndIsolation(t *testing.T) {
	t.Parallel()
	client, db := newTemplateResourceClient(t)
	owner := coderdtest.CreateFirstUser(t, client)
	ctx := t.Context()
	template := dbgen.Template(t, db, database.Template{OrganizationID: owner.OrganizationID, CreatedBy: owner.UserID})
	other := dbgen.Template(t, db, database.Template{OrganizationID: owner.OrganizationID, CreatedBy: owner.UserID})
	unbound, err := client.TemplateFoundation(ctx, template.ID)
	require.NoError(t, err)
	require.Nil(t, unbound)
	f, err := client.CreateFoundation(ctx, owner.OrganizationID, codersdk.CreateFoundationRequest{Name: "shared"})
	require.NoError(t, err)
	require.NotEqual(t, template.ID, f.ID)
	bound, err := client.SetTemplateFoundation(ctx, template.ID, codersdk.SetTemplateFoundationRequest{FoundationID: f.ID})
	require.NoError(t, err)
	require.Equal(t, template.ID, *bound.TemplateID)
	_, err = client.SetTemplateFoundation(ctx, other.ID, codersdk.SetTemplateFoundationRequest{FoundationID: f.ID})
	require.Equal(t, http.StatusConflict, coderdtest.SDKError(t, err).StatusCode())
	second, err := client.CreateFoundation(ctx, owner.OrganizationID, codersdk.CreateFoundationRequest{Name: "second"})
	require.NoError(t, err)
	_, err = client.SetTemplateFoundation(ctx, template.ID, codersdk.SetTemplateFoundationRequest{FoundationID: second.ID})
	require.Equal(t, http.StatusConflict, coderdtest.SDKError(t, err).StatusCode())
	foreignOrg := dbgen.Organization(t, db, database.Organization{})
	foreign, err := client.CreateFoundation(ctx, foreignOrg.ID, codersdk.CreateFoundationRequest{Name: "shared"})
	require.NoError(t, err, "names are organization-scoped")
	_, err = client.SetTemplateFoundation(ctx, other.ID, codersdk.SetTemplateFoundationRequest{FoundationID: foreign.ID})
	require.Equal(t, http.StatusNotFound, coderdtest.SDKError(t, err).StatusCode())
	_, err = client.Foundation(ctx, foreignOrg.ID, f.ID)
	require.Equal(t, http.StatusNotFound, coderdtest.SDKError(t, err).StatusCode())
	_, err = client.CreateFoundation(ctx, owner.OrganizationID, codersdk.CreateFoundationRequest{Name: "SHARED"})
	require.Equal(t, http.StatusConflict, coderdtest.SDKError(t, err).StatusCode())
	for _, tag := range []string{provisionersdk.TagOwner, provisionersdk.TagScope, provisionersdk.TagTemplateResources, provisionersdk.TagNetworkPolicyDestroy} {
		_, err = client.UpdateFoundation(ctx, owner.OrganizationID, f.ID, codersdk.UpdateFoundationRequest{Name: f.Name, ProvisionerTags: map[string]string{tag: "spoof"}})
		require.Equal(t, http.StatusBadRequest, coderdtest.SDKError(t, err).StatusCode())
	}
	require.NoError(t, client.DeleteTemplate(ctx, template.ID))
	retained, err := client.Foundation(ctx, owner.OrganizationID, f.ID)
	require.NoError(t, err, "Foundation management does not require a live template")
	require.Equal(t, f.ID, retained.ID)
	_, err = client.CreateFoundationRevision(ctx, owner.OrganizationID, f.ID, codersdk.CreateTemplateResourceRevisionRequest{Source: "# still editable"})
	require.NoError(t, err)
	list, err := client.Foundations(ctx, owner.OrganizationID)
	require.NoError(t, err)
	require.Len(t, list, 2)
}

func TestFoundationEditPublishPermissions(t *testing.T) {
	t.Parallel()
	client, db := newTemplateResourceClient(t)
	owner := coderdtest.CreateFirstUser(t, client)
	editor, user := coderdtest.CreateAnotherUser(t, client, owner.OrganizationID)
	ctx := t.Context()
	//nolint:gocritic // Install a custom role without requiring enterprise role management APIs.
	systemCtx := dbauthz.AsSystemRestricted(ctx)
	role, err := db.InsertCustomRole(dbauthz.As(ctx, rbac.Subject{ID: owner.UserID.String(), Roles: rbac.RoleIdentifiers{rbac.RoleOwner()}, Scope: rbac.ScopeAll}), database.InsertCustomRoleParams{Name: "foundation-editor", OrganizationID: uuid.NullUUID{UUID: owner.OrganizationID, Valid: true}, SitePermissions: database.CustomRolePermissions{}, UserPermissions: database.CustomRolePermissions{}, OrgPermissions: database.CustomRolePermissions{{ResourceType: "foundation", Action: "read"}, {ResourceType: "foundation", Action: "update"}}})
	require.NoError(t, err)
	_, err = db.UpdateMemberRoles(systemCtx, database.UpdateMemberRolesParams{UserID: user.ID, OrgID: owner.OrganizationID, GrantedRoles: []string{role.Name}})
	require.NoError(t, err)
	f, err := client.CreateFoundation(ctx, owner.OrganizationID, codersdk.CreateFoundationRequest{Name: "permissions"})
	require.NoError(t, err)
	revision, err := editor.CreateFoundationRevision(ctx, owner.OrganizationID, f.ID, codersdk.CreateTemplateResourceRevisionRequest{Source: "# editor draft"})
	require.NoError(t, err)
	plan, err := editor.CreateFoundationRun(ctx, owner.OrganizationID, f.ID, codersdk.CreateTemplateResourceRunRequest{RevisionID: revision.ID, Action: "plan"})
	require.NoError(t, err)
	require.NoError(t, editor.CancelFoundationRun(ctx, owner.OrganizationID, f.ID, plan.ID))
	_, err = editor.CreateFoundationRun(ctx, owner.OrganizationID, f.ID, codersdk.CreateTemplateResourceRunRequest{RevisionID: revision.ID, Action: "apply"})
	require.Equal(t, http.StatusNotFound, coderdtest.SDKError(t, err).StatusCode())
	apply, err := client.CreateFoundationRun(ctx, owner.OrganizationID, f.ID, codersdk.CreateTemplateResourceRunRequest{RevisionID: revision.ID, Action: "apply"})
	require.NoError(t, err)
	require.Equal(t, http.StatusNotFound, coderdtest.SDKError(t, editor.CancelFoundationRun(ctx, owner.OrganizationID, f.ID, apply.ID)).StatusCode())
	require.Equal(t, http.StatusNotFound, coderdtest.SDKError(t, editor.DeleteFoundation(ctx, owner.OrganizationID, f.ID)).StatusCode())
	job, err := db.GetProvisionerJobByID(systemCtx, apply.Job.ID)
	require.NoError(t, err)
	require.Equal(t, sql.NullTime{}, job.CanceledAt)
}
